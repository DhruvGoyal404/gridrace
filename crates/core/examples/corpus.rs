//! Regenerates the benchmark corpus in `data/`. Deterministic: same output on every run
//! and every machine (threads only split the seed range; results are kept in seed order).
//!
//!   cargo run --release -p gridrace-core --example corpus
//!
//! graded.txt: the first 100 puzzles of each difficulty tier among `minimal_puzzle(seed)`
//! for seeds 0..SWEEP.
//! hardest.txt: Beyond-tier puzzles made harder for the smart solvers. Start from the 50
//! Beyond puzzles of the sweep that cost MRV + DLX the most nodes, then hill-climb through
//! neighbouring minimal puzzles with the same solution (see `climb`), keeping a move only if
//! the puzzle stays Beyond and costs MRV + DLX more nodes. Ranking by both solvers keeps the
//! set from favouring either.
//! adversarial.txt: puzzles relabelled so the solution's first row reads 987654321, which
//! makes naive backtracking's first guess wrong in every first-row cell. The 20 that cost
//! brute force the most nodes among seeds 0..500.

use gridrace_core::generate::{minimal_puzzle, minimize};
use gridrace_core::human::{Difficulty, Grade, grade};
use gridrace_core::rng::Rng;
use gridrace_core::{Algorithm, Grid, Options, count_solutions, solve};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const SWEEP: u64 = 20_000;
const PER_TIER: usize = 100;
const HARDEST: usize = 50;
const CLIMB_STEPS: u32 = 200;
const ADVERSARIAL_FROM: u64 = 500;
const ADVERSARIAL: usize = 20;

fn nodes(p: &Grid, a: Algorithm) -> u64 {
    solve(p, a, Options::default()).unwrap().stats.nodes
}

fn smart_cost(p: &Grid) -> u64 {
    nodes(p, Algorithm::Mrv) + nodes(p, Algorithm::Dlx)
}

/// `f(seed)` for every seed, on all cores, in seed order.
fn sweep<T: Send>(seeds: u64, f: impl Fn(u64) -> T + Sync) -> Vec<T> {
    let threads = std::thread::available_parallelism().map_or(4, usize::from) as u64;
    let chunk = seeds.div_ceil(threads);
    std::thread::scope(|s| {
        let handles: Vec<_> = (0..threads)
            .map(|t| {
                let f = &f;
                s.spawn(move || {
                    (t * chunk..((t + 1) * chunk).min(seeds))
                        .map(f)
                        .collect::<Vec<T>>()
                })
            })
            .collect();
        handles
            .into_iter()
            .flat_map(|h| h.join().unwrap())
            .collect()
    })
}

/// Moves to a neighbouring minimal puzzle with the same solution while that makes it cost
/// the smart solvers more and keeps it Beyond. A move: empty one clue, add clues from the
/// solution until it's unique again, then minimise.
fn climb(start: Grid, solution: &Grid, seed: u64) -> (Grid, u64) {
    let mut rng = Rng::new(seed ^ 0xC11B);
    let (mut best, mut cost) = (start, smart_cost(&start));
    for _ in 0..CLIMB_STEPS {
        let mut next = best;
        let clues: Vec<usize> = (0..81).filter(|&c| next.0[c] != 0).collect();
        next.0[clues[rng.below(clues.len())]] = 0;
        while count_solutions(&next, 2) != Some(1) {
            let holes: Vec<usize> = (0..81).filter(|&c| next.0[c] == 0).collect();
            let hole = holes[rng.below(holes.len())];
            next.0[hole] = solution.0[hole];
        }
        let next = minimize(next, &mut rng);
        let next_cost = smart_cost(&next);
        if next_cost > cost && grade(&next).difficulty == Difficulty::Beyond {
            (best, cost) = (next, next_cost);
        }
    }
    (best, cost)
}

fn relabel(puzzle: &Grid, solution: &Grid) -> Grid {
    let mut map = [0u8; 10];
    for i in 0..9 {
        map[solution.0[i] as usize] = 9 - i as u8;
    }
    Grid(puzzle.0.map(|d| map[d as usize]))
}

fn technique(g: &Grade) -> &'static str {
    g.hardest.map_or("none", |t| t.name())
}

fn main() {
    let data = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data");
    let started = std::time::Instant::now();
    let phase = |name: &str| eprintln!("{name}: {:.1} s", started.elapsed().as_secs_f64());
    let all: Vec<(u64, Grid, Grid, Grade)> = sweep(SWEEP, |seed| {
        let (p, s) = minimal_puzzle(seed);
        (seed, p, s, grade(&p))
    });

    phase("sweep and grade");
    let mut graded = format!(
        "# GridRace graded corpus, generated by crates/core/examples/corpus.rs (MIT).\n\
         # The first {PER_TIER} puzzles of each tier among generate::minimal_puzzle(seed),\n\
         # seeds 0..{SWEEP}. Tier = hardest technique an easiest-first solve needs.\n\
         # Format: puzzle  # seed, tier, hardest technique\n"
    );
    let mut census = String::new();
    for tier in Difficulty::ALL {
        let of_tier: Vec<_> = all.iter().filter(|x| x.3.difficulty == tier).collect();
        let _ = write!(census, "{} {} ", tier.name(), of_tier.len());
        assert!(
            of_tier.len() >= PER_TIER,
            "only {} {tier:?} puzzles",
            of_tier.len()
        );
        for (seed, p, _, g) in &of_tier[..PER_TIER] {
            let _ = writeln!(
                graded,
                "{p}  # seed {seed}, {}, {}",
                tier.name(),
                technique(g)
            );
        }
    }

    let mut beyond: Vec<(u64, u64, &Grid, &Grid)> = all
        .iter()
        .filter(|x| x.3.difficulty == Difficulty::Beyond)
        .map(|(seed, p, s, _)| (smart_cost(p), *seed, p, s))
        .collect();
    beyond.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
    let starts = &beyond[..HARDEST];
    let climbed = sweep(HARDEST as u64, |i| {
        let (_, seed, p, s) = starts[i as usize];
        (seed, climb(*p, s, seed))
    });
    phase("hill-climb");
    let mut climbed: Vec<_> = climbed
        .into_iter()
        .map(|(seed, (p, cost))| (cost, seed, p))
        .collect();
    climbed.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
    let mut hardest = String::from(
        "# GridRace hardest corpus, generated by crates/core/examples/corpus.rs (MIT).\n\
         # Beyond-tier puzzles hill-climbed to cost MRV + DLX more nodes (see the example's docs).\n\
         # Format: puzzle  # start seed, MRV + DLX nodes\n",
    );
    for (cost, seed, p) in &climbed {
        let _ = writeln!(hardest, "{p}  # seed {seed}, {cost} nodes");
    }

    let mut scored: Vec<(u64, u64, Grid)> = sweep(ADVERSARIAL_FROM, |seed| {
        let (_, p, s, _) = &all[seed as usize];
        let hard = relabel(p, s);
        (nodes(&hard, Algorithm::Brute), seed, hard)
    });
    scored.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
    let mut adversarial = format!(
        "# GridRace adversarial corpus, generated by crates/core/examples/corpus.rs (MIT).\n\
         # minimal_puzzle(seed) for seeds 0..{ADVERSARIAL_FROM}, relabelled so the solution's first row\n\
         # is 987654321; the {ADVERSARIAL} with the most brute-force nodes. Format: puzzle  # seed, brute nodes\n"
    );
    for (n, seed, hard) in &scored[..ADVERSARIAL] {
        let _ = writeln!(adversarial, "{hard}  # seed {seed}, {n} nodes");
    }

    phase("adversarial");
    fs::write(data.join("graded.txt"), graded).unwrap();
    fs::write(data.join("hardest.txt"), hardest).unwrap();
    fs::write(data.join("adversarial.txt"), adversarial).unwrap();
    println!(
        "tiers in {SWEEP} seeds: {census}\nhardest: {} to {} MRV + DLX nodes (start set {} to {})",
        climbed.last().unwrap().0,
        climbed[0].0,
        starts.last().unwrap().0,
        starts[0].0
    );
}
