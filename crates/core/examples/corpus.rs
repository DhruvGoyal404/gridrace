//! Regenerates the benchmark corpus in `data/`. Deterministic: same output every run.
//!
//!   cargo run --release -p gridrace-core --example corpus
//!
//! generated.txt: line i is `minimal_puzzle(i)`.
//! adversarial.txt: generated puzzles with digits relabelled so the solution's first row
//! reads 9 8 7 6 5 4 3 2 1. Naive backtracking tries 1 to 9 in order, so every digit it
//! tries first is wrong. The 20 that cost brute force the most nodes are kept.

use gridrace_core::generate::minimal_puzzle;
use gridrace_core::{Algorithm, Grid, Options, solve};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const COUNT: u64 = 500;
const KEEP: usize = 20;

fn relabel(puzzle: &Grid, solution: &Grid) -> Grid {
    let mut map = [0u8; 10];
    for i in 0..9 {
        map[solution.0[i] as usize] = 9 - i as u8;
    }
    Grid(puzzle.0.map(|d| map[d as usize]))
}

fn main() {
    let data = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data");
    let mut generated = String::from(
        "# GridRace benchmark corpus, generated by crates/core/examples/corpus.rs (MIT).\n\
         # Line i (0-based, comments skipped) is generate::minimal_puzzle(i): unique and minimal.\n",
    );
    let mut scored = Vec::new();
    for seed in 0..COUNT {
        let (puzzle, solution) = minimal_puzzle(seed);
        writeln!(generated, "{puzzle}").unwrap();
        let hard = relabel(&puzzle, &solution);
        let nodes = solve(&hard, Algorithm::Brute, Options::default())
            .unwrap()
            .stats
            .nodes;
        scored.push((nodes, seed, hard));
    }
    scored.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
    let mut adversarial = String::from(
        "# GridRace adversarial corpus, generated by crates/core/examples/corpus.rs (MIT).\n\
         # minimal_puzzle(seed) relabelled so the solution's first row is 987654321,\n\
         # the 20 with the most brute-force nodes. Format: puzzle  # seed, brute nodes\n",
    );
    for (nodes, seed, hard) in &scored[..KEEP] {
        writeln!(adversarial, "{hard}  # seed {seed}, {nodes} nodes").unwrap();
    }
    fs::write(data.join("generated.txt"), generated).unwrap();
    fs::write(data.join("adversarial.txt"), adversarial).unwrap();
    println!(
        "wrote {COUNT} generated and {KEEP} adversarial puzzles; hardest: {} brute nodes",
        scored[0].0
    );
}
